#!/usr/bin/env python3
"""LN original numerical teaching experiments. No motor, AI model, or instrument is connected.

Run: python reproduce.py --output PATH
Python standard library only; optional SciPy comparison is performed when installed.
All CSV values are synthetic signals generated by the declared equations.
"""
import argparse,csv,json,math,random
from pathlib import Path

PARAMS={'R_ohm':2.0,'L_H':0.004,'Kt_Nm_per_A':0.05,'Ke_Vs_per_rad':0.05,
        'J_kg_m2':0.0002,'b_Nms_per_rad':0.0001,'bus_limit_V':12.0}

def derivative(x,u,load,p=PARAMS):
    i,w=x
    return ((u-p['R_ohm']*i-p['Ke_Vs_per_rad']*w)/p['L_H'],
            (p['Kt_Nm_per_A']*i-p['b_Nms_per_rad']*w-load)/p['J_kg_m2'])

def rk4(x,u,load,h,p=PARAMS):
    k1=derivative(x,u,load,p)
    k2=derivative(tuple(x[j]+h*k1[j]/2 for j in range(2)),u,load,p)
    k3=derivative(tuple(x[j]+h*k2[j]/2 for j in range(2)),u,load,p)
    k4=derivative(tuple(x[j]+h*k3[j] for j in range(2)),u,load,p)
    return tuple(x[j]+h*(k1[j]+2*k2[j]+2*k3[j]+k4[j])/6 for j in range(2))

def mean(xs):return sum(xs)/len(xs)
def rms(xs):return math.sqrt(mean([x*x for x in xs]))
def clamp(x,a,b):return min(b,max(a,x))
def write_csv(path,rows):
    with path.open('w',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=list(rows[0]));writer.writeheader();writer.writerows(rows)

def identification(folder):
    rng=random.Random(601)
    R,L,V=PARAMS['R_ohm'],PARAMS['L_H'],6.0
    tau=L/R;offset=.02;noise_sd=.002;dt=.0001
    rows=[]
    for n in range(201):
        t=n*dt;true=V/R*(1-math.exp(-t/tau));reading=true+offset+rng.gauss(0,noise_sd)
        rows.append(dict(time_s=t,current_true_A=true,current_raw_A=reading,current_corrected_A=reading-offset))
    write_csv(folder/'synthetic-locked-rotor.csv',rows)
    final=mean([r['current_corrected_A'] for r in rows if r['time_s']>=.014])
    r_fit=V/final
    selected=[r for r in rows if .0002<=r['time_s']<=.005]
    xs=[r['time_s'] for r in selected]
    ys=[math.log(1-r['current_corrected_A']/final) for r in selected]
    xm,ym=mean(xs),mean(ys)
    slope=sum((x-xm)*(y-ym) for x,y in zip(xs,ys))/sum((x-xm)**2 for x in xs)
    tau_fit=-1/slope;l_fit=tau_fit*r_fit
    train_error=rms([r['current_corrected_A']-V/r_fit*(1-math.exp(-r['time_s']*r_fit/l_fit)) for r in rows])
    # Deliberately changed resistance: a held-out operating condition, not training data.
    rv,vv=2.4,9.0
    validation=[]
    for n in range(201):
        t=n*dt;truth=vv/rv*(1-math.exp(-t*rv/L));prediction=vv/r_fit*(1-math.exp(-t*r_fit/l_fit))
        validation.append(dict(time_s=t,current_true_A=truth,current_predicted_A=prediction))
    write_csv(folder/'synthetic-holdout.csv',validation)
    holdout_error=rms([r['current_true_A']-r['current_predicted_A'] for r in validation])
    return {'source':'synthetic locked rotor RL current, seeded Gaussian measurement noise, known offset calibration',
      'R_fit_ohm':r_fit,'L_fit_H':l_fit,'tau_fit_s':tau_fit,'training_RMSE_A':train_error,
      'changed_resistance_ohm':rv,'holdout_RMSE_A':holdout_error,
      'claim':'Small training residual does not validate an unchanged resistance at another temperature/condition.'}

def convergence():
    t=.002;R,L,V=2.,.004,6.;exact=V/R*(1-math.exp(-t*R/L));runs=[]
    for dt in [.001,.0005,.0001]:
        i=0.
        for _ in range(round(t/dt)):i+=dt*(V-R*i)/L
        runs.append({'step_s':dt,'current_A':i,'absolute_error_A':abs(i-exact)})
    assert runs[-1]['absolute_error_A']<runs[0]['absolute_error_A']
    assert abs(exact-1.896361676485673)<1e-12
    # A local Euler pole of -1.5 is unstable even for a physically stable RL plant.
    pole=1-.005*R/L;assert abs(pole)>1
    x=(0.,0.)
    for _ in range(100000):x=rk4(x,12.,0.,.00001)
    wsteady=PARAMS['Kt_Nm_per_A']*12/(PARAMS['R_ohm']*PARAMS['b_Nms_per_rad']+PARAMS['Kt_Nm_per_A']*PARAMS['Ke_Vs_per_rad'])
    assert abs(x[1]-wsteady)<.3
    return {'locked_rotor_exact_current_at_2ms_A':exact,'Euler_runs':runs,
      'Euler_pole_at_5ms':pole,'full_motor_speed_after_1s_rad_s':x[1],
      'analytic_steady_speed_rad_s':wsteady}

def commands(faults):
    result=[]
    for seq in range(101):
        t=seq*.02
        if faults and .9<=t<=1.08:continue
        latency=.005+(.002 if seq%3==0 else 0.)
        if faults and seq==30:latency=.13
        result.append({'seq':seq,'created':t,'arrival':t+latency,'value':50.+20.*math.sin(2*math.pi*t)})
    return sorted(result,key=lambda r:(r['arrival'],r['seq']))

def replay(policy,faults,plant_dt=.00002):
    # A 1ms speed controller with RK4 plant substeps; no AI model or current-loop claim.
    T=.001;sub=round(T/plant_dt);assert abs(sub*plant_dt-T)<1e-12
    events=commands(faults);at=0;lastseq=-1;created=-1.;target=0.;reference=0.;integral=0.;x=(0.,0.)
    rows=[];rejected_old=0;rejected_stale=0;accepted=0
    for n in range(2001):
        t=n*T
        while at<len(events) and events[at]['arrival']<=t+1e-12:
            frame=events[at];at+=1
            if policy=='guarded' and frame['seq']<=lastseq:rejected_old+=1;continue
            if policy=='guarded' and t-frame['created']>.04:rejected_stale+=1;continue
            lastseq=frame['seq'];created=frame['created'];target=frame['value'];accepted+=1
        age=t-created if created>=0 else 1e6
        selected=target if policy=='arrival-order' or age<=.04 else 0.
        oldref=reference;reference+=clamp(selected-reference,-100*T,100*T)
        e=reference-x[1]
        # Both policies use exactly the same PI and feedforward; only packet acceptance differs.
        unsat=.1*e+integral+PARAMS['Ke_Vs_per_rad']*reference
        u=clamp(unsat,-12.,12.)
        if abs(unsat-u)<1e-12 or (unsat-u)*e<0:integral+=1.0*T*e
        load=.005 if t>=1.4 else 0.
        row={'time_s':t,'reference_rad_s':reference,'speed_rad_s':x[1],'current_A':x[0],
          'voltage_V':u,'load_Nm':load,'accepted_seq':lastseq,'command_age_s':age,
          'reference_acceleration_rad_s2':(reference-oldref)/T}
        rows.append(row)
        for _ in range(sub):x=rk4(x,u,load,plant_dt)
    valid=[r for r in rows if r['time_s']>=.1]
    age_values=[r['command_age_s'] for r in valid if r['command_age_s']<1e5]
    summary={'policy':policy,'faults':faults,'controller_period_s':T,'plant_step_s':plant_dt,
      'accepted_packets':accepted,'rejected_out_of_order':rejected_old,'rejected_stale':rejected_stale,
      'tracking_RMSE_to_applied_reference_rad_s':rms([r['speed_rad_s']-r['reference_rad_s'] for r in valid]),
      'max_abs_current_A':max(abs(r['current_A']) for r in rows),
      'max_reference_acceleration_rad_s2':max(abs(r['reference_acceleration_rad_s2']) for r in rows),
      'max_command_age_s':max(age_values),
      'end_speed_rad_s':rows[-1]['speed_rad_s'],
      'limits':'Script-generated plans emulate asynchronous command arrivals. No model inference, hardware, encoder noise, PWM ripple or current protection is represented.'}
    return rows,summary

def optional_scipy():
    try:
        import numpy as np
        from scipy.signal import StateSpace,lsim
    except ImportError:return {'executed':False,'reason':'NumPy/SciPy not installed; stdlib experiments still execute.'}
    p=PARAMS;A=np.array([[-p['R_ohm']/p['L_H'],-p['Ke_Vs_per_rad']/p['L_H']],
      [p['Kt_Nm_per_A']/p['J_kg_m2'],-p['b_Nms_per_rad']/p['J_kg_m2']]])
    B=np.array([[1/p['L_H']],[0.]])
    t=np.linspace(0,.1,1001);u=np.ones_like(t)*3
    _,y,_=lsim(StateSpace(A,B,np.eye(2),np.zeros((2,1))),u,t,interp=False)
    x=(0.,0.)
    for _ in range(1000):x=rk4(x,3.,0.,.0001)
    err=max(abs(x[j]-y[-1,j]) for j in range(2));assert err<1e-7,err
    return {'executed':True,'function':'scipy.signal.lsim','input_interpolation':'zero-order hold (interp=False)',
      'final_state_max_abs_difference_RK4_vs_lsim':err,'scipy_version':__import__('scipy').__version__}

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--output',default='experiment-output');args=ap.parse_args()
    out=Path(args.output);out.mkdir(parents=True,exist_ok=True)
    report={'provenance':'LN original synthetic teaching plant, not observations from any manufactured drive',
      'parameters':PARAMS,'convergence':convergence(),'identification':identification(out),'comparisons':[]}
    nominal=[]
    for faults in [False,True]:
        for policy in ['arrival-order','guarded']:
            rows,summary=replay(policy,faults);name=('fault' if faults else 'nominal')+'-'+policy
            write_csv(out/(name+'.csv'),rows);report['comparisons'].append(summary)
            if not faults:nominal.append(rows)
    assert all(abs(a['speed_rad_s']-b['speed_rad_s'])<1e-12 for a,b in zip(*nominal))
    fault=report['comparisons'][-1];assert fault['rejected_out_of_order']==1
    fine=replay('guarded',True,.00001)[1]
    report['step_halving']={'coarse_step_s':.00002,'fine_step_s':.00001,
      'end_speed_difference_rad_s':abs(fine['end_speed_rad_s']-fault['end_speed_rad_s'])}
    assert report['step_halving']['end_speed_difference_rad_s']<1e-6
    report['optional_scipy_crosscheck']=optional_scipy()
    (out/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps(report,ensure_ascii=False,indent=2))
if __name__=='__main__':main()
