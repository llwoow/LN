"""Build/validate the independently authored DC chapter diagnosis without changing existing practice IDs."""
from pathlib import Path
import argparse
import json
import math

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "courses/electrical-machines/assessment"
NAMES = ("dc-31-33.json", "dc-34-36.json", "dc-37-39.json", "dc-integrated.json")
MARK = ("// Generated by scripts/build-dc-chapter.py from the four chapter question sources; do not edit.\n"
        "window.LN_PRACTICE_BANK.questions.push(...")
SKILLS = {"建模", "因果与证据", "推导计算", "边界与反例", "迁移设计", "解释表达"}

def read_questions():
    questions = []
    for name in NAMES:
        src = json.loads((FOLDER / name).read_text(encoding="utf-8"))
        assert src["set"] == "dc-chapter-test", name
        questions.extend(src["questions"])
    assert len(questions) == 60, len(questions)
    ids = set()
    for q in questions:
        ident = q["id"]
        assert ident.startswith("dc-test-") and ident not in ids, ident
        ids.add(ident)
        assert q["course"] == "electrical-machines" and q["sections"][0] == "dc-chapter-test"
        assert len(q["sections"]) == 2 and q["sections"][1].startswith("dc-"), ident
        assert q["title"] and q["prompt"] and q["origin"] and q["hint"] and q["transfer"], ident
        assert len(q["steps"]) >= 3 and set(q["skills"]) <= SKILLS and q["skills"], ident
        assert q["type"] in {"single", "multi", "numeric", "open"}, ident
        if q["type"] in {"single", "multi"}:
            options = q["options"]
            optids = {o["id"] for o in options}
            assert len(options) >= 3 and len(optids) == len(options), ident
            assert all(o["text"] and o["feedback"] for o in options), ident
            assert set(q["answer"]) < optids, ident
            assert len(q["answer"]) == (1 if q["type"] == "single" else len(q["answer"])), ident
            if q["type"] == "multi":
                assert len(q["answer"]) >= 2, ident
        else:
            assert len(q["rubric"]) >= 3, ident
            if q["type"] == "numeric":
                assert math.isfinite(q["answer"]) and 0 < q["tolerance"] < 1 and q["unit"], ident
        if q.get("promptHtml"):
            assert "<svg" in q["promptHtml"] and "aria-label" in q["promptHtml"], ident
    distribution = {tag: sum(q["type"] == tag for q in questions)
                    for tag in ("single", "multi", "numeric", "open")}
    assert distribution == {"single": 21, "multi": 10, "numeric": 12, "open": 17}, distribution
    assert sum(bool(q.get("promptHtml")) for q in questions) == 5
    return questions

def render(questions):
    sources = [s for s in json.loads((ROOT / "courses/practice/sources.json").read_text(encoding="utf-8"))["sources"]
               if s["id"].startswith("dc-")]
    assert len(sources) == 2
    extra = json.dumps(sources, ensure_ascii=False, separators=(",", ":"))
    # Direct repo preview has the last committed generated bank.js; static builds regenerate
    # bank.js from sources.json. Deduplicate to keep both routes consistent.
    return (MARK + json.dumps(questions, ensure_ascii=False, separators=(",", ":"))
            + ");\nwindow.LN_PRACTICE_BANK.sources.push(..."
            + extra
            + ".filter(s => !window.LN_PRACTICE_BANK.sources.some(old => old.id === s.id)));\n")

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    questions = read_questions()
    existing = json.loads((ROOT / "courses/practice/bank.json").read_text(encoding="utf-8"))
    overlap = {q["id"] for q in existing["questions"]} & {q["id"] for q in questions}
    assert not overlap, f"Question ID collision: {overlap}"
    target = FOLDER / "dc-chapter.js"
    output = render(questions)
    if args.check:
        assert target.is_file() and target.read_text(encoding="utf-8") == output, "DC chapter compiled quiz is stale"
    else:
        target.write_text(output, encoding="utf-8")
    print(f"DC chapter assessment: {len(questions)} independent question records; "
          "no claim of pedagogical measurement validation.")

if __name__ == "__main__":
    main()
